/** An [Icon] as a tinted Drawable that scales to whatever bounds it gets. */
internal class IconDrawable(private val icon: Icon, color: Int) : Drawable() {
    private val paint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
        this.color = color
        style = Paint.Style.FILL
    }
    private val scaled = Path()
    private val matrix = Matrix()

    var color: Int
        get() = paint.color
        set(value) {
            paint.color = value
            invalidateSelf()
        }

    override fun onBoundsChange(bounds: android.graphics.Rect) {
        super.onBoundsChange(bounds)
        val source = icon.parsed ?: return
        val scale = minOf(bounds.width(), bounds.height()) / 24f
        matrix.setScale(scale, scale)
        matrix.postTranslate(bounds.left + (bounds.width() - 24 * scale) / 2f, bounds.top + (bounds.height() - 24 * scale) / 2f)
        source.transform(matrix, scaled)
    }

    override fun draw(canvas: Canvas) {
        if (icon.parsed != null) canvas.drawPath(scaled, paint)
    }

    override fun setAlpha(alpha: Int) {
        paint.alpha = alpha
        invalidateSelf()
    }

    override fun setColorFilter(colorFilter: ColorFilter?) {
        paint.colorFilter = colorFilter
        invalidateSelf()
    }

    @Deprecated("Deprecated in Java")
    override fun getOpacity(): Int = PixelFormat.TRANSLUCENT
}
